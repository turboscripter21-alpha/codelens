/** Tool, dependency and cache folders: never project source, skipped wherever they appear. */
const IGNORED_DIRS = new Set([
  "node_modules", ".git", ".next", ".nuxt", ".svelte-kit", ".turbo", ".vercel", ".cache", ".parcel-cache",
  "coverage", "__pycache__", ".pytest_cache", ".mypy_cache", ".venv", "venv", ".tox", "bower_components", "jspm_packages",
  ".gradle", ".idea", ".vscode", "Pods", "DerivedData",
]);
/**
 * Folder names that are *often* build output but just as often real source (build scripts,
 * a lib's out/ folder, Python "env" packages). They are skipped only when the folder itself
 * shows generated files (see `generatedDirs`); otherwise every file in them is kept.
 */
const OUTPUT_DIRS = new Set(["dist", "build", "out", "target", "release", "env"]);
/** A file that proves its output folder was generated by a tool. */
const GENERATED_FILE = /(\.map|[.-]min\.(js|css|mjs)|\.(chunk|bundle)\.(js|css)|[.-][0-9a-f]{8,}\.(js|css|mjs)|\.d\.ts|\.(class|o|obj|pyc|rlib|rmeta|tsbuildinfo))$/i;
const GENERATED_NAME = new Set(["cachedir.tag", ".rustc_info.json", "asset-manifest.json", "build-manifest.json", "pyvenv.cfg", "_redirects.generated"]);

/**
 * Output-named folders (prefix paths like "dist" or "packages/ui/build") that contain at least
 * one generated file. Everything under them is skipped as "build-output".
 */
export function generatedDirs(paths: string[]): Set<string> {
  const out = new Set<string>();
  for (const p of paths) {
    const parts = p.split("/");
    const name = parts[parts.length - 1].toLowerCase();
    if (!GENERATED_FILE.test(name) && !GENERATED_NAME.has(name)) continue;
    for (let i = 0; i < parts.length - 1; i++) {
      if (OUTPUT_DIRS.has(parts[i].toLowerCase()) || (name === "pyvenv.cfg" && i === parts.length - 2)) {
        out.add(parts.slice(0, i + 1).join("/"));
        break;
      }
    }
  }
  return out;
}
const VENDOR_DIRS = new Set(["vendor", "third_party", "third-party", "thirdparty", "external"]);

