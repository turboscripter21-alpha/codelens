/** Files whose contents we never read or return. They become Vault buildings, by name only. */
export function isSecretPath(path: string): boolean {
  const name = path.slice(path.lastIndexOf("/") + 1).toLowerCase();
  if (name === ".env" || name.startsWith(".env.") || name.startsWith(".env-") || name.startsWith(".env_") || name.endsWith(".env") || name === ".envrc") return true;
  if (/^id_(rsa|dsa|ecdsa|ed25519)(_sk)?(\.pub)?$/.test(name)) return true;
  if (/\.(pem|key|p12|pfx|keystore|jks|kdbx|asc|gpg|ovpn|crt|cer|der|p8|ppk|tfvars|tfstate|tfstate\.backup)$/.test(name)) return true;
  if ([".npmrc", ".pypirc", ".netrc", ".htpasswd", "credentials", "credentials.json", "service-account.json", "secrets.json", "secrets.yml", "secrets.yaml", ".git-credentials",
    ".dev.vars", ".pgpass", ".s3cfg", ".boto", ".terraformrc", "terraform.rc", "kubeconfig", ".yarnrc.yml", ".dockercfg"].includes(name)) return true;
  const lower = path.toLowerCase();
  if (/(^|\/)\.(aws|kube|docker|ssh|gnupg)\/[^/]+$/.test(lower) && name !== "readme.md") return true; // ~/.aws/credentials, .kube/config, .docker/config.json, .ssh/*
  if (/(^|[._-])secrets?([._-]|$)/.test(name) && /\.(json|ya?ml|toml|txt|ini)$/.test(name)) return true;
  return false;
}

export function isLockfile(path: string): boolean {
  return LOCKFILES.has(path.slice(path.lastIndexOf("/") + 1).toLowerCase());
}

/** Audio / video files that open in a player (HTML5 <audio> / <video>), with their content type. */
const MEDIA_MIME: Record<string, string> = {
  mp3: "audio/mpeg", wav: "audio/wav", ogg: "audio/ogg", m4a: "audio/mp4", flac: "audio/flac",
  mp4: "video/mp4", webm: "video/webm",
};
/** Largest media file CodeLens will play (bytes). */
export const MEDIA_MAX_BYTES = 10 * 1024 * 1024;
export function mediaMime(path: string): string | null {
  const e = extOf(path);
  return Object.prototype.hasOwnProperty.call(MEDIA_MIME, e) ? MEDIA_MIME[e] : null;
}

/** Images that open in the image viewer (as an <img> from a blob: URL; SVG is never inlined into the page). */
const IMAGE_MIME: Record<string, string> = {
  png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", gif: "image/gif", webp: "image/webp",
  bmp: "image/bmp", ico: "image/x-icon", avif: "image/avif", svg: "image/svg+xml",
};
/** Largest image CodeLens will show (bytes). */
export const IMAGE_MAX_BYTES = 5 * 1024 * 1024;
export function imageMime(path: string): string | null {
  const e = extOf(path);
  return Object.prototype.hasOwnProperty.call(IMAGE_MIME, e) ? IMAGE_MIME[e] : null;
}

/** Friendly type name for a binary file (shown on its card), e.g. "PDF document", "Font (WOFF2)". */
export function binaryTypeOf(path: string): string {
  const e = extOf(path);
  const up = e.toUpperCase();
  if (e === "pdf") return "PDF document";
  if (["woff", "woff2", "ttf", "otf", "eot"].includes(e)) return `Font (${up})`;
  if (["zip", "gz", "tgz", "bz2", "xz", "7z", "rar", "tar", "jar", "war"].includes(e)) return `Archive (${up})`;
  if (["apk", "ipa", "dmg", "iso"].includes(e)) return `App / disk image (${up})`;
  if (["exe", "dll", "so", "dylib", "bin", "o", "a", "lib", "class", "pyc", "pyo", "wasm", "node"].includes(e)) return `Compiled binary (${up})`;
  if (["doc", "docx", "xls", "xlsx", "ppt", "pptx"].includes(e)) return `Office document (${up})`;
  if (["sqlite", "db"].includes(e)) return `Database (${up})`;
  if (["glb", "gltf", "fbx", "obj", "blend"].includes(e)) return `3D model (${up})`;
  if (["tif", "tiff", "psd", "heic"].includes(e)) return `Image (${up}, not shown in browsers)`;
  if (["mov", "avi", "mkv"].includes(e)) return `Video (${up}, not playable here)`;
  if (imageMime(path)) return `Image (${up})`;
  const m = mediaMime(path);
  if (m) return (m.startsWith("video/") ? "Video" : "Audio") + ` (${up})`;
  return e ? `Binary file (${up})` : "Binary file";
}

export function isBinaryExt(path: string): boolean {
  return BINARY_EXT.has(extOf(path));
}

/**
 * Returns why a (safe, normalized) path is skipped entirely, or null if it should be kept.
 * `generated` comes from `generatedDirs` over the whole listing; without it, output-named
 * folders (dist, build, out...) are kept.
 */
export function skipReason(path: string, generated?: Set<string>): SkipReason | null {
  const parts = path.split("/");
  for (let i = 0; i < parts.length - 1; i++) {
    if (parts[i] === "__MACOSX") return "os-metadata";
    if (IGNORED_DIRS.has(parts[i])) return "ignored-dir";
    if (VENDOR_DIRS.has(parts[i].toLowerCase())) return "vendored";
    if (generated?.size && generated.has(parts.slice(0, i + 1).join("/"))) return "build-output";
  }
  const name = parts[parts.length - 1].toLowerCase();
  if (name === ".ds_store" || name === "thumbs.db" || name === "desktop.ini" || name.startsWith("._")) return "os-metadata";
  if (/[.-]min\.(js|css|mjs)$/.test(name) || /\.(map|bundle\.js|chunk\.js)$/.test(name)) return "minified";
  return null;
}

/**
 * Normalize an archive / upload path and reject anything unsafe:
 * absolute paths, drive letters, "..", empty or control characters.
 * Returns null for unsafe paths (they are counted as skipped "unsafe-path").
 */
export function normalizePath(raw: string): string | null {
  if (typeof raw !== "string" || raw.length === 0 || raw.length > 1024) return null;
  if (/[\u0000-\u001f]/.test(raw)) return null;
  const p = raw.replace(/\\/g, "/");
  if (p.startsWith("/") || /^[a-zA-Z]:/.test(p) || p.startsWith("~")) return null;
  const out: string[] = [];
  for (const seg of p.split("/")) {
    if (seg === "" || seg === ".") continue;
    if (seg === "..") return null;
    out.push(seg);
  }
  return out.length ? out.join("/") : null;
}

/**
 * If every path shares the same top folder (zip root, "repo-main/"), strip it. Repeats for
 * a nested copy of the root ("proj/proj/src/..."), and ignores macOS "__MACOSX/" metadata when deciding.
 * `root` is the innermost shared folder name.
 */
export function stripCommonRoot(paths: string[]): { root: string | null; strip: (p: string) => string } {
  const real = paths.filter((p) => !p.startsWith("__MACOSX/"));
  let prefix = "";
  let root: string | null = null;
  for (let depth = 0; depth < 8 && real.length; depth++) {
    const rest = real.map((p) => p.slice(prefix.length));
    const first = rest[0].split("/")[0];
    if (!rest.every((p) => p.includes("/") && p.split("/")[0] === first)) break;
    // Below the zip root, only strip a folder that repeats the root's name ("proj/proj/",
    // "repo-main/repo/"), never a real shared folder like "src/".
    if (root !== null && !(first.toLowerCase().startsWith(root.toLowerCase()) || root.toLowerCase().startsWith(first.toLowerCase()))) break;
    prefix += first + "/";
    root = first;
  }
  if (!prefix) return { root: null, strip: (p) => p };
  return { root, strip: (p) => (p.startsWith(prefix) ? p.slice(prefix.length) : p) };
}

/** True if the bytes look binary (a NUL byte in the first 8 KB). */
export function looksBinary(bytes: Uint8Array): boolean {
  const n = Math.min(bytes.length, 8000);
  for (let i = 0; i < n; i++) if (bytes[i] === 0) return true;
  return false;
}
