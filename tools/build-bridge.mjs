// Bundles lib/bridge/index.ts (analyzer, importers, city plan) into public/app/codelens-bridge.js
// for the static CodeLens pages. Runs before `next dev` / `next build` (see package.json).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
await build({
  entryPoints: [path.join(root, "lib/bridge/index.ts")],
  outfile: path.join(root, "public/app/codelens-bridge.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  sourcemap: false,
  legalComments: "none",
  tsconfig: path.join(root, "tsconfig.json"),
  logLevel: "warning",
  banner: { js: "/* CodeLens bridge: generated by tools/build-bridge.mjs from lib/bridge/index.ts. Do not edit. */" },
});
console.log("built public/app/codelens-bridge.js");
